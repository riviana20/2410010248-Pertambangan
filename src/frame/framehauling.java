    private void btnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSimpanActionPerformed
        db.simpanHauling(txtLoading.getText(), txtDumping.getText(),
                txtLokasiLoading.getText(), txtLokasiHauling.getText(),
                txtWaktu.getText());
        bersih();
    }//GEN-LAST:event_btnSimpanActionPerformed

    private void btnCariActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCariActionPerformed
        try {
            String[] d = db.cariHauling(Integer.parseInt(txtId.getText().trim()));
            if (d != null) {
                txtLoading.setText(d[0]);
                txtDumping.setText(d[1]);
                txtLokasiLoading.setText(d[2]);
                txtLokasiHauling.setText(d[3]);
                // buang ".0" di belakang detik bila ada
                txtWaktu.setText(d[4].length() > 19 ? d[4].substring(0, 19) : d[4]);
            } else {
                JOptionPane.showMessageDialog(this, "Data tidak ditemukan");
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "ID harus berupa angka");
        }
    }//GEN-LAST:event_btnCariActionPerformed

    private void btnUbahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUbahActionPerformed
        try {
            db.ubahHauling(Integer.parseInt(txtId.getText().trim()),
                    txtLoading.getText(), txtDumping.getText(),
                    txtLokasiLoading.getText(), txtLokasiHauling.getText(),
                    txtWaktu.getText());
            bersih();
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Isi ID dengan angka (gunakan tombol Cari)");
        }
    }//GEN-LAST:event_btnUbahActionPerformed

    private void btnHapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHapusActionPerformed
        try {
            db.hapusHauling(Integer.parseInt(txtId.getText().trim()));
            bersih();
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Isi ID dengan angka");
        }
    }//GEN-LAST:event_btnHapusActionPerformed

    private void btnBersihActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBersihActionPerformed
        bersih();
    }//GEN-LAST:event_btnBersihActionPerformed

